"""Render docs/society/RESULTS.md and docs/society/SCHEMA.md, so no number or column in the society documentation is typed by hand.

RESULTS.md reads artifacts/society/<key>/{evaluation,peak_evaluation,anomalies,shap_global}.json and data/society/processed/societies.json.
SCHEMA.md reads the SQLAlchemy models (the society tables) and the Alembic migration list.

    python scripts/make_society_docs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts" / "society"
PROC = ROOT / "data" / "society" / "processed"
OUT = ROOT / "docs" / "society" / "RESULTS.md"
HORIZONS = ("1", "6", "12", "24", "168")
HLABEL = {"1": "1 h", "6": "6 h", "12": "12 h", "24": "24 h", "168": "7 days"}
NAMES = {"naive": "Naive (last value)", "seasonal_naive_24": "Seasonal naive 24 h", "seasonal_naive_168": "Seasonal naive 168 h", "seasonal_naive_336": "Seasonal naive 336 h",
         "linear": "Linear regression", "random_forest": "Random Forest", "xgboost": "XGBoost", "xgboost_weather": "XGBoost + observed weather"}
nm = lambda k: NAMES.get(k, k)  # noqa: E731


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def f(x, d=1):
    return "–" if x is None else f"{x:,.{d}f}"


SOCIETY_TABLES = ("societies", "buildings", "meters", "consumption_records", "society_hourly", "society_models", "forecast_results", "anomaly_events", "society_reports")


def schema() -> None:
    sys.path.insert(0, str(ROOT))
    from backend.app import models  # noqa: F401
    from backend.app.db import Base

    L = ["# Society database schema (generated)", "",
         "Generated by `scripts/make_society_docs.py` from the SQLAlchemy models in `backend/app/models.py`; created by Alembic migration `0002`. "
         "The household tables of the original project (users, datasets, readings, jobs, model_versions, forecasts, anomalies, tariffs, ...) are unchanged and shared: "
         "users, jobs, tariffs and the audit log serve both parts of the application. The ER diagram of all tables is `docs/diagrams/er_diagram.png`.", ""]
    for name in SOCIETY_TABLES:
        t = Base.metadata.tables[name]
        L += [f"## `{name}`", "", "| Column | Type | Key | Nullable |", "|---|---|---|---|"]
        for c in t.columns:
            key = ", ".join(x for x, on in (("PK", c.primary_key), (f"FK to {next(iter(c.foreign_keys)).column.table.name}" if c.foreign_keys else "", bool(c.foreign_keys)), ("unique", bool(c.unique))) if on and x)
            L.append(f"| `{c.name}` | {str(c.type)} | {key} | {'yes' if c.nullable else 'no'} |")
        extra = [f"unique ({', '.join(col.name for col in con.columns)})" for con in t.constraints if con.__class__.__name__ == "UniqueConstraint"]
        extra += [f"index {ix.name} ({', '.join(col.name for col in ix.columns)})" for ix in t.indexes]
        if extra:
            L += ["", "Constraints and indexes: " + "; ".join(sorted(extra)) + "."]
        L.append("")
    (ROOT / "docs" / "society" / "SCHEMA.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/society/SCHEMA.md")


def main() -> None:
    schema()
    meta = load(PROC / "societies.json")
    keys = [s["key"] for s in meta["societies"]]
    info = {s["key"]: s for s in meta["societies"]}
    ev = {k: load(ART / k / "evaluation.json") for k in keys}
    L: list[str] = ["# Society results (generated)", "",
                    "Generated by `scripts/make_society_docs.py` from the saved evaluation files in `artifacts/society/`. Nothing here is typed by hand. "
                    "Units: demand in kW (hourly mean, numerically equal to kWh per hour). Test period = the last six months of the data, scored once; "
                    "the model for each horizon was chosen by mean absolute error over four expanding-window cross-validation blocks that precede the test period "
                    "(baselines compete in that selection). MAPE ignores hours whose actual demand is below 1 kW. See `docs/society/04_models_and_evaluation.md` for the protocol.", ""]

    L += ["## 1. The seven communities", "", "| Community | Site time zone | Buildings | Floor area (m²) | Valid hours | Mean demand (kW) | Test period |", "|---|---|---|---|---|---|---|"]
    for k in keys:
        s, e = info[k], ev[k]
        tp = e["protocol"]["test_period"] if e else ["–", "–"]
        L.append(f"| {s['name']} | {s['timezone']} | {s['buildings']} | {f(s['floor_area_sqm'], 0)} | {s['valid_hours']:,} of {s['hours']:,} ({100 * s['valid_hours'] / s['hours']:.1f}%) | {f(s['mean_kw'], 0)} | {tp[0][:10]} to {tp[1][:10]} |")
    if meta.get("rejected_sites"):
        L += ["", "Sites rejected by the validity rule (not enough clean residential meters): " + "; ".join(f"{r['site']} ({r['reason']})" for r in meta["rejected_sites"]) + ".", ""]

    L += ["", "## 2. Selected model per horizon, scored once on the test period", "",
          "`Model` is the configuration with the lowest cross-validated MAE (it can be a baseline). `Best baseline` is the best of the naive / seasonal-naive rules by the same criterion. "
          "`Gain` = MAE reduction of the selected model over that baseline on the test period; the bootstrap interval is for the paired difference in daily MAE (negative = the model is better).", ""]
    L += ["| Community | Horizon | Model | MAE (kW) | RMSE (kW) | MAPE (%) | R² | Best baseline | Baseline MAE (kW) | Gain | 95% interval of MAE difference (kW) |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in keys:
        for h in HORIZONS:
            r = ev[k]["horizons"].get(h) if ev[k] else None
            if not r:
                continue
            m = r["best_overall_by_cv"]
            t, b = r["test"][m], r["test"][r["best_baseline_by_cv"]]
            bs = r.get("bootstrap_vs_best_baseline")
            ci = f"{bs['ci95_low']:.1f} to {bs['ci95_high']:.1f}" if bs and not r["best_overall_is_baseline"] else "model is the baseline"
            gain = "–" if r["best_overall_is_baseline"] else f"{(b['mae'] - t['mae']) / b['mae'] * 100:.1f}%"
            L.append(f"| {k} | {HLABEL[h]} | {nm(m)} | {f(t['mae'])} | {f(t['rmse'])} | {f(t['mape_pct'], 2)} | {f(t['r2'], 3)} | {nm(r['best_baseline_by_cv'])} | {f(b['mae'])} | {gain} | {ci} |")

    L += ["", "## 3. Every model on the test period: MAE in kW", ""]
    for k in keys:
        if not ev[k]:
            continue
        cols = list(ev[k]["horizons"]["24"]["test"].keys())
        L += [f"### {info[k]['name']}", "", "| Model | " + " | ".join(HLABEL[h] for h in HORIZONS) + " |", "|---|" + "---|" * len(HORIZONS)]
        for c in cols:
            row = []
            for h in HORIZONS:
                r = ev[k]["horizons"].get(h)
                v = r["test"].get(c, {}).get("mae") if r else None
                mark = "**" if r and v is not None and c == r["best_overall_by_cv"] else ""
                row.append(f"{mark}{f(v)}{mark}")
            L.append(f"| {nm(c)} | " + " | ".join(row) + " |")
        L += ["", "Bold = the configuration chosen by cross-validation for that horizon.", ""]

    L += ["## 4. Does the 24-hour forecast find each day's peak?", "",
          "For every held-out test day with at least 22 scored hours: the day's highest forecast hour against the day's highest measured hour, using forecasts issued 24 h ahead. "
          "The baseline is the best simple rule at 24 h. A lower peak MAE is better; the hit rates say how often the forecast peak falls in the right hour.", "",
          "| Community | Days | Mean daily peak (kW) | Model peak MAE (kW) | Baseline peak MAE (kW) | Gain | Peak hour exact: model / baseline | Within 1 h | Within 2 h |", "|---|---|---|---|---|---|---|---|---|"]
    for k in keys:
        p = load(ART / k / "peak_evaluation.json")
        if not p or not p.get("days"):
            continue
        L.append(f"| {k} | {p['days']} | {f(p['mean_actual_peak_kw'], 0)} | {f(p['model']['peak_mae_kw'])} | {f(p['baseline']['peak_mae_kw'])} | {f(p['mae_improvement_vs_baseline_pct'])}% | "
                 f"{f(p['model']['peak_hour_exact_pct'], 0)}% / {f(p['baseline']['peak_hour_exact_pct'], 0)}% | {f(p['model']['peak_hour_within_1h_pct'], 0)}% / {f(p['baseline']['peak_hour_within_1h_pct'], 0)}% | "
                 f"{f(p['model']['peak_hour_within_2h_pct'], 0)}% / {f(p['baseline']['peak_hour_within_2h_pct'], 0)}% |")

    L += ["", "## 5. Anomaly alerts (no ground-truth labels exist, so no detection accuracy is claimed)", "",
          "| Community | Whole-society events | Low | Medium | High | Hours flagged | Building-level events |", "|---|---|---|---|---|---|---|"]
    for k in keys:
        a = load(ART / k / "anomalies.json")
        if not a:
            continue
        s = a["society_summary"]
        nb = sum(v["events"] for v in a["building_summary"].values())
        L.append(f"| {k} | {s['events']} | {s['events_by_severity'].get('low', 0)} | {s['events_by_severity'].get('medium', 0)} | {s['events_by_severity'].get('high', 0)} | {s['flagged_pct_of_valid']:.1f}% of valid hours | {nb:,} |")

    L += ["", "## 6. What drives the 24-hour forecast (TreeSHAP, share of mean |SHAP|, test rows)", "", "| Community | Model | Feature group shares |", "|---|---|---|"]
    for k in keys:
        s = load(ART / k / "shap_global.json")
        if not s or "24" not in s["horizons"]:
            continue
        g = s["horizons"]["24"]
        L.append(f"| {k} | {nm(g['model'])} | " + "; ".join(f"{a} {v:.0f}%" for a, v in list(g["group_share_pct"].items())[:4]) + " |")
    L += ["", "SHAP values describe what the fitted model uses, not physical causes.", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
