"""Render docs/api/API_REFERENCE.md from the running application's routes (access rules read from the real dependencies)."""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests" / "integration"))

from conftest import make_settings  # noqa: E402

from backend.app.main import API_PREFIX, create_app  # noqa: E402
from backend.app.security import current_user_dep  # noqa: E402


def access_of(route) -> str:
    deps = []

    def walk(d):
        for sub in d.dependencies:
            deps.append(sub.call)
            walk(sub)

    walk(route.dependant)
    for call in deps:
        roles = getattr(call, "allowed_roles", None)
        if roles:
            return "role: " + " or ".join(roles)
    return "signed-in user" if current_user_dep in deps else "public"


def main() -> None:
    app = create_app(make_settings(Path(tempfile.mkdtemp())))
    rows = []

    def add(path: str, route) -> None:
        for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
            doc = (route.endpoint.__doc__ or "").strip().splitlines()[0] if route.endpoint.__doc__ else ""
            rows.append((path, method, access_of(route), route.status_code or 200, doc, route.name))

    for route in app.routes:
        if hasattr(route, "original_router"):  # routers included under /api/v1 (route paths are stored relative to the prefix)
            for sub in route.original_router.routes:
                if hasattr(sub, "methods"):
                    add(API_PREFIX + sub.path, sub)
        elif hasattr(route, "methods") and route.path.startswith("/health"):
            add(route.path, route)
    rows.sort()
    lines = ["# API reference", "",
             "Generated by `scripts/make_api_reference.py` from the application's routes; the access column is read from the real "
             "dependencies, so it cannot disagree with the code. Machine-readable schema: `docs/api/openapi.json`. "
             "Interactive docs at `/docs` are available in `dev` and `test` environments only.", "",
             "Authentication: `Authorization: Bearer <JWT>` obtained from `POST /api/v1/auth/login`. Error bodies are `{\"detail\": ...}`; "
             "validation errors are 422, unknown or foreign resources 404, wrong role 403, rate limit 429 with `Retry-After`.", "",
             "| Method | Path | Access | Success | Handler | Notes |", "|---|---|---|---|---|---|"]
    for path, method, access, status, doc, name in rows:
        lines.append(f"| {method} | `{path}` | {access} | {status} | `{name}` | {doc} |")
    out = ROOT / "docs" / "api" / "API_REFERENCE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} with {len(rows)} operations")


if __name__ == "__main__":
    main()
