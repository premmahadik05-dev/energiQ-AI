"""Write the real data behind the chart on the sign-in page: one week of measured demand and the 24-hour-ahead forecast.

The sign-in page is shown before anyone is signed in, and every API route needs a login, so the chart cannot fetch its data. It is built from a small
file generated here from the saved evaluation of the Fox community (Building Data Genome Project 2, CC BY-SA 4.0): the forecast of the model that the
cross-validation selected for the 24-hour horizon, on the held-out test period, never trained on those hours.

Which week: among all complete Monday-to-Sunday weeks of the held-out period the one whose mean absolute percentage error is the MEDIAN, so the chart shows
a typical week and not the best or the worst one.

    python scripts/make_login_chart_data.py     # writes frontend/src/components/auth/loginDemand.ts
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SOCIETY = "fox"
OUT = ROOT / "frontend" / "src" / "components" / "auth" / "loginDemand.ts"


def main() -> None:
    folder = ROOT / "artifacts" / "society" / SOCIETY
    evaluation = json.loads((folder / "evaluation.json").read_text())
    horizon = evaluation["horizons"]["24"]
    model = horizon["best_overall_by_cv"]
    test_period = evaluation["protocol"]["test_period"]
    pred = pd.read_csv(folder / "predictions_h24.csv.gz", parse_dates=["target_time"]).set_index("target_time")
    pred = pred[["y_true", model]].dropna()
    pred = pred.rename(columns={model: "forecast"})

    weeks = []
    for start in pd.date_range(pred.index.min().normalize(), pred.index.max(), freq="W-MON"):
        chunk = pred.loc[start : start + pd.Timedelta(hours=167)]
        if len(chunk) != 168 or not (chunk.index == pd.date_range(start, periods=168, freq="h")).all():
            continue
        err = (chunk["y_true"] - chunk["forecast"]).abs()
        weeks.append({"start": start, "mape": float((err / chunk["y_true"]).mean() * 100), "mae": float(err.mean()), "chunk": chunk})
    if not weeks:
        raise SystemExit("no complete week in the held-out predictions")
    weeks.sort(key=lambda w: w["mape"])
    pick = weeks[len(weeks) // 2]
    chunk = pick["chunk"]

    body = f"""// GENERATED by scripts/make_login_chart_data.py from artifacts/society/{SOCIETY}/ (do not edit by hand).
// Real data: measured hourly demand of the BDG2 "{SOCIETY}" residential community and the {model.replace('_', ' ')} forecast made 24 hours ahead,
// from the held-out test period. The week is the median-error complete week of {len(weeks)} such weeks.
export const LOGIN_DEMAND = {{
  society: 'BDG2 site {SOCIETY.capitalize()} residential community',
  source: 'Building Data Genome Project 2, CC BY-SA 4.0',
  model: '{model.replace('_', ' ')}',
  horizonHours: 24,
  weekStart: '{pick['start'].strftime('%Y-%m-%d')}',
  candidateWeeks: {len(weeks)},
  mapePct: {pick['mape']:.1f},
  maeKw: {pick['mae']:.0f},
  testPeriod: '{test_period[0]} to {test_period[1]}',
  measured: {json.dumps([round(float(v), 1) for v in chunk['y_true']])} as readonly number[],
  forecast: {json.dumps([round(float(v), 1) for v in chunk['forecast']])} as readonly number[],
}} as const;
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body)
    print(f"wrote {OUT.relative_to(ROOT)}: week {pick['start']:%Y-%m-%d}, MAPE {pick['mape']:.1f} %, MAE {pick['mae']:.0f} kW, model {model}, {len(weeks)} candidate weeks")


if __name__ == "__main__":
    main()
